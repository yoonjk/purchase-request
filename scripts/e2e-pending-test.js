const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');

async function runPendingApprovalE2ETest() {
  const timestamp = '20261012175517';
  const screenshotsDir = path.join(__dirname, '..', 'docs', 'screenshots', timestamp);
  if (!fs.existsSync(screenshotsDir)) {
    fs.mkdirSync(screenshotsDir, { recursive: true });
  }

  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({
    viewport: { width: 1280, height: 900 }
  });
  const page = await context.newPage();

  const report = {
    testId: timestamp,
    testDate: new Date().toISOString(),
    steps: [],
    success: true,
    data: {}
  };

  try {
    console.log('Step 1: 대상 URL(http://localhost:8080/purchases.html) 접속');
    await page.goto('http://localhost:8080/purchases.html', { waitUntil: 'networkidle' });
    const screen1 = path.join(screenshotsDir, '01_initial_screen.png');
    await page.screenshot({ path: screen1, fullPage: true });
    report.steps.push({
      step: 1,
      name: '구매 승인 화면 접속',
      status: 'PASS',
      screenshot: `docs/screenshots/${timestamp}/01_initial_screen.png`
    });

    console.log('Step 2 & 3: 자동 생성된 Test run ID 확인 및 Requester 입력');
    const autoGeneratedRunId = await page.inputValue('#createTestRunId');
    console.log(`자동 생성된 Test run ID: ${autoGeneratedRunId}`);
    report.data.initialTestRunId = autoGeneratedRunId;
    if (!autoGeneratedRunId) {
      throw new Error('Test run ID가 자동으로 생성되지 않았습니다.');
    }

    await page.fill('#createRequester', 'bob-ui-tester');

    console.log('Step 4 & 5: Amount(1500000) 및 Budget(2000000) 입력');
    await page.fill('#createAmount', '1500000');
    await page.fill('#createBudget', '2000000');

    const screen2 = path.join(screenshotsDir, '02_form_filled.png');
    await page.screenshot({ path: screen2, fullPage: true });
    report.steps.push({
      step: 2,
      name: '입력값 설정 (Requester: bob-ui-tester, Amount: 1500000, Budget: 2000000, Test Run ID: ' + autoGeneratedRunId + ')',
      status: 'PASS',
      screenshot: `docs/screenshots/${timestamp}/02_form_filled.png`
    });

    console.log('Step 6: Create request 버튼 클릭 및 응답 대기');
    const [response] = await Promise.all([
      page.waitForResponse(res => res.url().includes('/api/purchase-requests') && res.request().method() === 'POST'),
      page.click('#createBtn')
    ]);

    const postResponseData = await response.json();
    console.log('생성 응답 데이터:', postResponseData);
    report.data.created = postResponseData;

    await page.waitForSelector('#statusBadgeContainer span');
    await page.waitForTimeout(500);

    const screen3 = path.join(screenshotsDir, '03_create_success.png');
    await page.screenshot({ path: screen3, fullPage: true });

    // Step 7: 승인 상태 PENDING_APPROVAL 검증
    const statusText = await page.textContent('#statusBadgeContainer');
    console.log(`승인 상태 배지 텍스트: ${statusText.trim()}`);
    const isPendingApproval = postResponseData.status === 'PENDING_APPROVAL' && statusText.includes('PENDING_APPROVAL');
    if (!isPendingApproval) {
      throw new Error(`승인 상태가 PENDING_APPROVAL이 아닙니다. (실제: ${postResponseData.status})`);
    }
    report.steps.push({
      step: 3,
      name: '생성 결과 승인 상태 PENDING_APPROVAL 검증',
      status: 'PASS',
      expected: 'PENDING_APPROVAL',
      actual: postResponseData.status,
      screenshot: `docs/screenshots/${timestamp}/03_create_success.png`
    });

    // Step 8: Request ID 및 Test run ID 조회 입력 필드 자동 반영 확인
    const lookupRequestId = await page.inputValue('#requestId');
    const lookupRunId = await page.inputValue('#lookupRun');
    console.log(`조회 필드 자동 반영 값 - Request ID: ${lookupRequestId}, Test Run ID: ${lookupRunId}`);

    const isRequestIdSynced = String(lookupRequestId) === String(postResponseData.request_id);
    const isRunIdSynced = lookupRunId === postResponseData.test_run_id;

    if (!isRequestIdSynced || !isRunIdSynced) {
      throw new Error(`조회 필드 자동 반영 불일치 (RequestId: ${lookupRequestId} vs ${postResponseData.request_id}, RunId: ${lookupRunId} vs ${postResponseData.test_run_id})`);
    }
    report.steps.push({
      step: 4,
      name: 'Request ID 및 Test run ID 조회 필드 자동 연동 검증',
      status: 'PASS',
      requestId: lookupRequestId,
      testRunId: lookupRunId
    });

    // Step 9: Find request 버튼 클릭 및 조회 검증
    console.log('Step 9: Find request 버튼 클릭 및 데이터 조회');
    const [lookupResponse] = await Promise.all([
      page.waitForResponse(res => res.url().includes('/api/purchase-requests/') && res.request().method() === 'GET'),
      page.click('#lookup')
    ]);

    const getResponseData = await lookupResponse.json();
    console.log('조회 응답 데이터:', getResponseData);
    report.data.lookup = getResponseData;

    await page.waitForTimeout(500);
    const screen4 = path.join(screenshotsDir, '04_lookup_success.png');
    await page.screenshot({ path: screen4, fullPage: true });

    // Step 10: 생성 결과와 조회 결과 데이터 정합성 비교 (Request ID, Test run ID, Amount, Budget, Status)
    const isMatched =
      getResponseData.request_id === postResponseData.request_id &&
      getResponseData.requester === postResponseData.requester &&
      getResponseData.test_run_id === postResponseData.test_run_id &&
      Number(getResponseData.amount) === Number(postResponseData.amount) &&
      Number(getResponseData.budget) === Number(postResponseData.budget) &&
      getResponseData.status === postResponseData.status;

    if (!isMatched) {
      throw new Error('생성 데이터와 조회 데이터가 일치하지 않습니다.');
    }

    report.steps.push({
      step: 5,
      name: '생성 결과와 조회 결과 데이터 정합성 검증 (Request ID, Test Run ID, Amount, Budget, Status)',
      status: 'PASS',
      screenshot: `docs/screenshots/${timestamp}/04_lookup_success.png`
    });

    console.log('PENDING_APPROVAL End-to-End 테스트 성공 완료!');
  } catch (err) {
    console.error('테스트 실패:', err.message);
    report.success = false;
    report.error = err.message;
  } finally {
    await browser.close();
    fs.writeFileSync(path.join(__dirname, '..', 'docs', `test-result-${timestamp}.json`), JSON.stringify(report, null, 2));
    console.log('테스트 결과 JSON 저장 완료');
  }
}

runPendingApprovalE2ETest();
